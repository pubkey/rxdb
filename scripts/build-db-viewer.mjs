/**
 * Bundles the database viewer into ONE self contained HTML file.
 *
 * The page is published with the docs at https://rxdb.info/html/db-viewer.html
 * and loaded into an iframe by `rxdb/plugins/db-viewer`. Everything it needs
 * has to be inside that single file: it must run with no further requests,
 * because it is embedded into other peoples apps on other origins.
 */
import { execSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

const rootPath = join(dirname(fileURLToPath(import.meta.url)), '..');
const bundlePath = join(rootPath, 'db-viewer', 'dist', 'db-viewer.js');
const outputPath = join(rootPath, 'docs-src', 'static', 'html', 'db-viewer.html');

console.log('# bundling the database viewer');
execSync('npx webpack --config config/webpack.db-viewer.config.js', {
    cwd: rootPath,
    stdio: 'inherit'
});

const script = readFileSync(bundlePath, 'utf-8');

/**
 * `</script` and `<!--` inside a string or a regex of the bundle would end the
 * inline script tag early. Escaping the slash keeps both valid JavaScript.
 */
function inlineSafe(code) {
    return code
        .replace(/<\/script/gi, '<\\/script')
        .replace(/<!--/g, '<\\!--');
}

const html = `<!DOCTYPE html>
<html lang="en">

<head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width,initial-scale=1" />
    <meta name="robots" content="noindex" />
    <title>RxDB Database Viewer</title>
    <!--
        This page is the UI of the RxDB database viewer.
        https://rxdb.info/db-viewer.html

        It is loaded as a cross-site iframe inside the apps of RxDB users and
        talks to the RxDatabase of the embedding page over postMessage.
        No data of that database ever leaves the browser, and this page makes
        no network request of its own once it is loaded.

        IMPORTANT: Do NOT add Google Tag Manager or any other analytics script
        here, for the same reasons that are written down in dev-mode-iframe.html:
        the hits are unjoinable under storage partitioning, there is no consent
        UI inside an embedded frame, and third party scripts would make this
        page a target for adblockers inside other peoples applications.

        This file is GENERATED by scripts/build-db-viewer.mjs from the sources
        in db-viewer/. Do not edit it by hand.
    -->
    <style>
        html, body { margin: 0; padding: 0; height: 100%; background: #0D0F18; }
        #root { height: 100%; }
    </style>
</head>

<body>
    <div id="root"></div>
    <noscript>
        The RxDB database viewer needs JavaScript to run.
    </noscript>
    <script>${inlineSafe(script)}</script>
</body>

</html>
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, html);

const bytes = statSync(outputPath).size;
const gzipped = gzipSync(Buffer.from(html)).length;
console.log(
    '# wrote ' + outputPath.replace(rootPath + '/', '') +
    ' (' + Math.round(bytes / 1024) + ' KB, ' + Math.round(gzipped / 1024) + ' KB gzipped)'
);
