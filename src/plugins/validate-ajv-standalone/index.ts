/**
 * This plugin validates documents before they can be inserted into the RxCollection.
 * Instead of compiling the JSON schema at runtime, it uses validators
 * that were precompiled at build time with the ajv standalone tools.
 * This keeps the ajv compiler out of the production bundle.
 * @link https://ajv.js.org/standalone.html
 */
import type {
    RxDocumentData,
    RxJsonSchema,
    RxStorage,
    RxStorageInstanceCreationParams
} from '../../types/index.d.ts';
import { wrappedValidateStorageFactory } from '../../plugin-helpers.ts';
import { createRxSchema } from '../../rx-schema.ts';
import { newRxError } from '../../rx-error.ts';
import { defaultHashSha256 } from '../utils/index.ts';
import { INTERNAL_STORE_SCHEMA_TITLE } from '../../rx-database-internal-store.ts';
import { META_INSTANCE_SCHEMA_TITLE } from '../../replication-protocol/meta-instance.ts';
import { RX_LOCAL_DOCUMENT_SCHEMA_TITLE } from '../local-documents/local-documents-helper.ts';

/**
 * A validate function as it is generated by the ajv standalone tools.
 * Returns true if the data is valid, otherwise false
 * and the errors are set to the errors property.
 */
export type AjvStandaloneValidateFunction = {
    (data: any): boolean;
    errors?: any[] | null;
};

export type ValidatorBySchemaHash = {
    [schemaHash: string]: AjvStandaloneValidateFunction;
};

/**
 * Storage instances of these schemas are created by RxDB itself
 * and not by the developer, so they are not validated.
 */
const INTERNAL_SCHEMA_TITLES = new Set([
    INTERNAL_STORE_SCHEMA_TITLE,
    META_INSTANCE_SCHEMA_TITLE,
    RX_LOCAL_DOCUMENT_SCHEMA_TITLE
]);

export function getSchemaHashForStandaloneValidation(
    storageSchema: RxJsonSchema<any>
): Promise<string> {
    return defaultHashSha256(JSON.stringify(storageSchema));
}

/**
 * Use this at build time.
 * Returns the full JSON schema exactly as the storage will get it
 * (with the RxDB internal fields like _deleted, _rev and _meta)
 * together with its hash.
 * Compile the returned jsonSchema with the ajv standalone tools
 * and store the validator under the returned hash.
 */
export async function getStandaloneValidationSchema<RxDocType>(
    schema: RxJsonSchema<RxDocType>
): Promise<{
    hash: string;
    jsonSchema: RxJsonSchema<RxDocumentData<RxDocType>>;
}> {
    const jsonSchema = createRxSchema(schema, defaultHashSha256).jsonSchema;
    return {
        hash: await getSchemaHashForStandaloneValidation(jsonSchema),
        jsonSchema
    };
}

export function wrappedValidateAjvStandaloneStorage<Internals, InstanceCreationOptions>(
    args: {
        storage: RxStorage<Internals, InstanceCreationOptions>;
        validatorBySchemaHash: ValidatorBySchemaHash;
    }
): RxStorage<Internals, InstanceCreationOptions> {
    const validatorBySchemaString = new Map<string, AjvStandaloneValidateFunction>();
    const validatedStorage = wrappedValidateStorageFactory(
        (schema) => {
            const validator = validatorBySchemaString.get(JSON.stringify(schema)) as AjvStandaloneValidateFunction;
            return (docData: RxDocumentData<any>) => {
                if (validator(docData)) {
                    return [];
                } else {
                    return validator.errors as any;
                }
            };
        },
        'ajv-standalone'
    )({ storage: args.storage });

    return Object.assign(
        {},
        validatedStorage,
        {
            async createStorageInstance<RxDocType>(
                params: RxStorageInstanceCreationParams<RxDocType, InstanceCreationOptions>
            ) {
                if (params.schema.title && INTERNAL_SCHEMA_TITLES.has(params.schema.title)) {
                    return args.storage.createStorageInstance(params);
                }
                const schemaString = JSON.stringify(params.schema);
                const schemaHash = await getSchemaHashForStandaloneValidation(params.schema);
                const validator = args.validatorBySchemaHash[schemaHash];
                if (!validator) {
                    throw newRxError('VD3', {
                        collection: params.collectionName,
                        schemaHash,
                        schema: params.schema
                    });
                }
                validatorBySchemaString.set(schemaString, validator);
                return validatedStorage.createStorageInstance(params);
            }
        }
    );
}
